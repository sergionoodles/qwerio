//! Cell editing transitions; widgets and rendering live in sibling modules.
use super::TableGridDelegate;
use super::cell_widgets::{ActiveEdit, text_with_date};
use chrono::NaiveDate;
use gpui_kit::{App, Context, Focusable as _, SharedString, Window};
use qwerio_app::table_edits::GridRow;
use qwerio_core::cell_input::{CellEditor, boolean_state, cell_editor};
use qwerio_core::edit::check_editable;
use qwerio_core::value::Value;

pub(super) const DEFAULT_LABEL: &str = "DEFAULT";
pub(super) type GridContext<'a> =
    Context<'a, gpui_kit::component::table::TableState<TableGridDelegate>>;
pub(super) type Grid = gpui_kit::component::table::TableState<TableGridDelegate>;

/// How a cell can be edited.
#[derive(Clone, Copy)]
pub(super) struct CellEditing {
    pub(super) kind: CellEditor,
    pub(super) is_nullable: bool,
}

impl TableGridDelegate {
    pub(super) fn is_editing(&self, row: usize, column: usize) -> bool {
        self.editing
            .as_ref()
            .is_some_and(|edit| edit.row == row && edit.column == column)
    }

    /// The browser index of a grid row showing a loaded row.
    pub(super) fn loaded_row(&self, row: usize) -> Option<usize> {
        match self.edit_session.pending().grid_row(row) {
            GridRow::Loaded(index) => Some(index),
            GridRow::New(_) => None,
        }
    }

    fn column_name(&self, column: usize) -> Option<&str> {
        self.browser
            .columns()
            .get(column)
            .map(|column| column.name.as_str())
    }

    /// The value shown for a cell: its staged edit, or the loaded value.
    /// `None` for new-row cells left to their default.
    pub(super) fn cell_value(&self, row: usize, column: usize) -> Option<&Value> {
        match self.edit_session.pending().grid_row(row) {
            GridRow::New(index) => self
                .edit_session
                .pending()
                .new_row_value(index, self.column_name(column)?),
            GridRow::Loaded(index) => self
                .edit_session
                .pending()
                .value(&self.browser, index, column)
                .or_else(|| self.browser.rows().get(index)?.get(column)),
        }
    }

    /// Whether a cell of a new row is left to the column's default.
    pub(super) fn is_default_cell(&self, row: usize, column: usize) -> bool {
        matches!(self.edit_session.pending().grid_row(row), GridRow::New(_))
            && self.cell_value(row, column).is_none()
    }

    /// Whether a cell has a staged value: an edit of a loaded cell, or a
    /// value set in a new row.
    pub(super) fn is_modified(&self, row: usize, column: usize) -> bool {
        match self.edit_session.pending().grid_row(row) {
            GridRow::New(_) => self.cell_value(row, column).is_some(),
            GridRow::Loaded(index) => self
                .edit_session
                .pending()
                .value(&self.browser, index, column)
                .is_some(),
        }
    }

    /// Whether the table's rows can be edited at all.
    pub(super) fn is_editable(&self) -> bool {
        !self.is_reloading
            && self
                .browser
                .details()
                .is_some_and(|details| check_editable(details).is_ok())
    }

    /// The editor for a cell, or why it cannot be edited.
    pub(super) fn cell_editing(
        &self,
        row: usize,
        column: usize,
    ) -> Result<CellEditing, SharedString> {
        if self.is_reloading {
            return Err("Wait for the table to finish loading".into());
        }
        if self.edit_session.is_saving() {
            return Err("Wait for the current save to finish before editing".into());
        }
        let details = self.browser.details().ok_or("The table is still loading")?;
        check_editable(details).map_err(|reason| SharedString::from(reason.message()))?;

        let info = self
            .browser
            .columns()
            .get(column)
            .and_then(|descriptor| details.column(&descriptor.name))
            .ok_or("Refresh the table to edit this column")?;

        if info.generated {
            return Err(format!("{} is generated by the database", info.name).into());
        }

        let kind = cell_editor(info).ok_or_else(|| {
            SharedString::from(format!("{} values cannot be edited inline", info.type_name))
        })?;

        if let GridRow::Loaded(index) = self.edit_session.pending().grid_row(row) {
            if self.browser.row_identity(index).is_none() {
                return Err("This row cannot be identified; refresh the table".into());
            }

            if self.edit_session.pending().is_deleted(&self.browser, index) {
                return Err("This row is marked for deletion".into());
            }
        }

        Ok(CellEditing {
            kind,
            is_nullable: info.nullable,
        })
    }

    /// Whether a column is drawn as checkboxes: boolean columns of editable
    /// tables.
    pub(super) fn is_checkbox_column(&self, column: usize) -> bool {
        self.is_editable()
            && self
                .browser
                .details()
                .zip(self.browser.columns().get(column))
                .and_then(|(details, descriptor)| details.column(&descriptor.name))
                .and_then(cell_editor)
                == Some(CellEditor::Boolean)
    }

    /// Opens the editor of a cell, or toggles a boolean cell. Another open
    /// edit is committed first.
    pub(super) fn begin_edit(
        &mut self,
        row: usize,
        column: usize,
        window: &mut Window,
        cx: &mut GridContext,
    ) {
        if self.is_editing(row, column) {
            return;
        }

        if !self.commit_edit(cx) {
            return;
        }

        let editing = match self.cell_editing(row, column) {
            Ok(editing) => editing,
            Err(message) => {
                self.edit_error = Some(message);
                cx.notify();
                return;
            }
        };

        let value = self.cell_value(row, column).cloned();

        if editing.kind == CellEditor::Boolean {
            let checked = !value.as_ref().and_then(boolean_state).unwrap_or(false);
            self.set_boolean(row, column, checked, cx);
            return;
        }

        self.edit_error = None;
        self.editing = Some(ActiveEdit::new(
            row,
            column,
            editing,
            value.as_ref(),
            window,
            cx,
        ));
        cx.notify();
    }

    /// Stages the open edit. Returns `false`, keeping the editor open with
    /// the error, when the text is not a valid value.
    pub(super) fn commit_edit(&mut self, cx: &mut GridContext) -> bool {
        let Some(edit) = self.editing.as_mut() else {
            return true;
        };

        let text = edit.input.read(cx).value().to_string();

        match edit.draft.parse_change(&text) {
            Ok(value) => {
                let (row, column) = (edit.row, edit.column);
                if let Some(value) = value {
                    self.stage(row, column, value);
                }
                self.close_edit(cx);
                true
            }
            Err(message) => {
                edit.error = Some(message.clone().into());
                self.edit_error = Some(message.into());
                cx.notify();
                false
            }
        }
    }

    /// Whether leaving would lose work: staged edits, or text typed into the
    /// open editor.
    pub(super) fn has_unsaved_changes(&self, cx: &App) -> bool {
        let is_typing = self
            .editing
            .as_ref()
            .is_some_and(|edit| edit.draft.has_changes(edit.input.read(cx).value().as_ref()));

        !self.edit_session.pending().is_empty() || is_typing
    }

    pub(super) fn close_edit(&mut self, cx: &mut GridContext) {
        self.editing = None;
        self.edit_error = None;
        self.apply_deferred_pages(cx);
        cx.notify();
    }

    /// Stages a value for a cell of a loaded or new row.
    fn stage(&mut self, row: usize, column: usize, value: Value) {
        let Some(name) = self.column_name(column).map(str::to_owned) else {
            return;
        };

        match self.edit_session.pending().grid_row(row) {
            GridRow::New(index) => {
                self.edit_session
                    .edit_pending(|edits| edits.set_new_row_value(index, name, value));
            }
            GridRow::Loaded(index) => {
                self.edit_session
                    .edit_pending(|edits| edits.stage(&self.browser, index, column, value));
            }
        }
    }

    pub(super) fn set_boolean(
        &mut self,
        row: usize,
        column: usize,
        checked: bool,
        cx: &mut GridContext,
    ) {
        if let Err(message) = self.cell_editing(row, column) {
            self.edit_error = Some(message);
            cx.notify();
            return;
        }

        // Loaded booleans may be stored as integers; checking the loaded
        // state again drops the edit.
        let loaded_row = self.loaded_row(row);
        let loaded_state = loaded_row
            .and_then(|index| self.browser.rows().get(index)?.get(column))
            .and_then(boolean_state);

        match loaded_row {
            Some(index) if loaded_state == Some(checked) => {
                self.edit_session
                    .edit_pending(|edits| edits.revert(&self.browser, index, column));
            }
            _ => self.stage(row, column, Value::Bool(checked)),
        }

        self.edit_error = None;
        cx.notify();
    }

    /// Stages NULL for a cell when its column allows it.
    pub(super) fn set_null(&mut self, row: usize, column: usize, cx: &mut GridContext) {
        let editing = match self.cell_editing(row, column) {
            Ok(editing) => editing,
            Err(message) => {
                self.edit_error = Some(message);
                cx.notify();
                return;
            }
        };

        if !editing.is_nullable {
            self.edit_error = Some("This column does not allow NULL".into());
            cx.notify();
            return;
        }

        if self.is_editing(row, column) {
            self.editing = None;
        }

        self.stage(row, column, Value::Null);
        self.edit_error = None;
        cx.notify();
    }

    /// Drops a cell's staged value: a loaded cell shows its loaded value
    /// again, a new-row cell goes back to its default.
    pub(super) fn revert_cell(&mut self, row: usize, column: usize, cx: &mut GridContext) {
        if self.edit_session.is_saving() {
            return;
        }
        if self.is_editing(row, column) {
            self.editing = None;
        }

        match (
            self.edit_session.pending().grid_row(row),
            self.column_name(column),
        ) {
            (GridRow::New(index), Some(name)) => {
                let name = name.to_owned();
                self.edit_session
                    .edit_pending(|edits| edits.reset_new_row_value(index, &name));
            }
            (GridRow::Loaded(index), _) => {
                self.edit_session
                    .edit_pending(|edits| edits.revert(&self.browser, index, column));
            }
            (GridRow::New(_), None) => {}
        }

        self.edit_error = None;
        cx.notify();
    }

    pub(super) fn toggle_calendar(&mut self, cx: &mut GridContext) {
        if let Some(edit) = self.editing.as_mut() {
            edit.is_calendar_open = !edit.is_calendar_open;
            cx.notify();
        }
    }

    /// Puts a date picked in the calendar into the editor. Dates are done;
    /// date-times keep their time of day for further editing.
    pub(super) fn pick_date(
        &mut self,
        date: NaiveDate,
        window: &mut Window,
        cx: &mut GridContext,
    ) -> bool {
        let Some(edit) = self.editing.as_mut() else {
            return false;
        };

        let current = edit.input.read(cx).value().to_string();
        let text = text_with_date(edit.draft.kind, &current, date);
        edit.is_calendar_open = false;
        edit.input.update(cx, |input, cx| {
            input.set_value(text, window, cx);
            input.focus(window, cx);
        });

        edit.draft.kind == CellEditor::Date
    }
}

/// Keyboard navigation away from an open editor commits it first, and stays
/// put while its text is invalid. The grid takes focus back from the closed
/// editor so that further keys keep moving.
pub(super) fn commit_before_moving(table: &mut Grid, window: &mut Window, cx: &mut GridContext) {
    if !table.delegate_mut().commit_edit(cx) {
        cx.stop_propagation();
        return;
    }

    focus_grid(table, window, cx);
}

/// Returns keyboard focus to the grid after an editor closes.
pub(super) fn focus_grid(table: &mut Grid, window: &mut Window, cx: &mut GridContext) {
    let handle = table.focus_handle(cx);
    window.focus(&handle, cx);
}
